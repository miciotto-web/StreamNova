  /** Tutte le radici GTS incluse nel fallback, come [X509Certificate]. */
  fun certificates(): List<X509Certificate> = parsePems(
    listOf(GTS_ROOT_R1_PEM, GTS_ROOT_R2_PEM, GTS_ROOT_R3_PEM, GTS_ROOT_R4_PEM)
  )

  /** Decodifica una lista di PEM in [X509Certificate]; fallisce se un PEM è invalido. */
  fun parsePems(pems: List<String>): List<X509Certificate> {
    val factory = CertificateFactory.getInstance("X.509")
    return pems.map { pem ->
      factory.generateCertificate(pem.trim().byteInputStream()) as X509Certificate
    }
  }

  /** Trust manager di sistema (le anchor predefinite della piattaforma). */
  fun systemTrustManager(): X509TrustManager {
    val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
    tmf.init(null as KeyStore?)
    return tmf.trustManagers.filterIsInstance<X509TrustManager>().first()
  }

  /** Trust manager costruito SU un insieme esplicito di anchor (nessuna altra fonte). */
  fun trustManagerFor(anchors: List<X509Certificate>): X509TrustManager {
    val keyStore = KeyStore.getInstance(KeyStore.getDefaultType()).apply {
      load(null, null)
      anchors.forEachIndexed { index, cert -> setCertificateEntry("anchor-$index", cert) }
    }
    val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
    tmf.init(keyStore)
    return tmf.trustManagers.filterIsInstance<X509TrustManager>().first()
  }

  private val combinedTm: X509TrustManager by lazy {
    trustManagerFor(systemTrustManager().acceptedIssuers.toList() + certificates())
  }

  /**
   * Trust manager di fallback testabile: anchor COMBINATE (sistema + radici GTS).
   * È lo stesso trust manager usato da [fallbackSocketFactory] tramite
   * [com.example.data.network.tlsFallback].
   */
  fun combinedTrustManager(): X509TrustManager = combinedTm

  private val combinedSslContext: SSLContext by lazy {
    SSLContext.getInstance("TLS").apply { init(null, arrayOf<TrustManager>(delegatingTm), null) }
  }

  /**
   * Trust manager ibrido: prova le anchor COMBINATE (sistema + GTS) e, solo se
   * la validazione combinata fallisce, riprova con quella di sistema pura. In
   * pratica accetta tutto ciò che il sistema accetta, più le catene GTS.
   */
  private val delegatingTm: X509TrustManager = object : X509TrustManager {
    override fun checkClientTrusted(chain: Array<X509Certificate>?, authType: String?) {
      systemTrustManager().checkClientTrusted(chain, authType)
    }

    override fun checkServerTrusted(chain: Array<X509Certificate>?, authType: String?) {
      try {
        combinedTm.checkServerTrusted(chain, authType)
      } catch (combined: CertificateException) {
        try {
          systemTrustManager().checkServerTrusted(chain, authType)
        } catch (system: CertificateException) {
          // Nessuna delle due validazioni passa: prevale l'errore COMBINATO (che
          // include già il tentativo con le radici GTS aggiuntive).
          throw combined
        }
      }
    }

    override fun getAcceptedIssuers(): Array<X509Certificate> =
      combinedTm.acceptedIssuers
  }

  /** Fabbrica TLS (socket factory + trust manager) del fallback, per i client OkHttp. */
  fun fallbackSocketFactory(): Pair<javax.net.ssl.SSLSocketFactory, X509TrustManager> =
    Pair(combinedSslContext.socketFactory, delegatingTm)
}

/**
 * Applica il TLS fallback (anchor di sistema + radici GTS) a un builder OkHttp:
 * i client che lo usano validano le catene Cloudflare/Google Trust Services
 * anche sui vecchi Android TV privi delle radici GTS nel negozio di sistema.
 */
fun OkHttpClient.Builder.tlsFallback(): OkHttpClient.Builder {
  val (factory, trustManager) = TlsRoots.fallbackSocketFactory()
  return sslSocketFactory(factory, trustManager)
}
